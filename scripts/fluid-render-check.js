import assert from 'node:assert/strict';
import * as THREE from 'three';
import { World } from '../shared/world.js';
import { BLOCK } from '../shared/blocks.js';

const { FluidRenderer }=await import('../public/js/render/fluidRenderer.js');
const { meshChunk }=await import('../public/js/render/mesher.js');
const world=new World(1,16,16,{sizeY:16,minY:0});
world.setBlock(2,2,2,BLOCK.BRONZE_PIPE);world.setBlock(3,2,2,BLOCK.BRONZE_PIPE);
assert.equal(meshChunk(world,world.getChunk(0,0,0)).opaque.index.count,108,
  'Connected pipes retained caps or overlapping inner faces');
const renderer=new FluidRenderer(new THREE.Scene());
const tank={x:0,y:0,z:0,kind:'tank',mode:null,fluid:'steam',amount:40,capacity:4000,fill:0.01};
const pipe={x:1,y:0,z:0,kind:'pipe',mode:1};
renderer.sync([tank,pipe]);
const faceDots=renderer.pipeMeshes.get(1);
assert.equal(faceDots.geometry.index.count,216,'Mode dots do not cover every center face');
const dotX=faceDots.geometry.getAttribute('position').array.filter((_,i)=>i%3===0);
assert.ok(dotX.some(x=>Math.abs(x-1.701)<1e-6),'Mode dots are not on the center surface');
assert.equal(renderer.modeAt(1,0,0),1);
const glass=renderer.tankMeshes[0];
renderer.sync([{...tank,amount:60,fill:0.015},pipe]);
assert.equal(renderer.tankMeshes[0],glass,'Steam amount update rebuilt the glass mesh');
const visual=[...renderer.steamVisuals.values()][0];
assert.ok(visual.mesh.geometry.index.count>0);
const heights=visual.mesh.geometry.getAttribute('position').array.filter((_,i)=>i%3===1);
assert.ok(Math.max(...heights)>=1,'Steam was rendered as a tiny liquid-height strip');
renderer.update(0.05);assert.ok(visual.mesh.material.opacity>0);
renderer.sync([{...tank,fluid:null,amount:0,fill:0},pipe]);
renderer.update(0.05);
assert.ok(visual.mesh.material.opacity>0,'Steam vanished in one snapshot');
renderer.update(2);
assert.equal(renderer.steamVisuals.size,0);
renderer.sync([tank,{...pipe,mode:0}]);
assert.equal(renderer.pipeMeshes.size,0);
renderer.sync([tank,{...pipe,mode:2}]);
assert.ok(renderer.pipeMeshes.get(2));
renderer.dispose();
console.log('OK: flush six-face pipe dots and smoothly fading full-volume tank steam');
